#!/usr/bin/env python3
"""Bind MMPose COCO17 *human* reference poses to real SAM 2 video identities.

Reference-only. Never creates, warps, extrapolates or resamples painted sprites.
SAM 2 actor mask frames must already have been generated by the official model.
"""
from __future__ import annotations
import hashlib
import json
import math
from pathlib import Path
import re
from PIL import Image
import numpy as np
from mmpose_bridge import COCO_17, NECESSARY, MotionError, point, read_guide, gait_metrics


def _predictions(record):
    pred = record.get('predictions', [])
    if isinstance(pred, dict): pred = [pred]
    if isinstance(pred, list) and len(pred) == 1 and isinstance(pred[0], list): pred = pred[0]
    if not isinstance(pred, list): raise MotionError('Invalid MMPose predictions structure')
    return pred


def _load_mask_sequence(directory:Path, resolution:tuple[int,int]):
    directory=Path(directory).resolve()
    if not directory.is_dir():raise MotionError('Missing real tracked SAM 2 masks: '+str(directory))
    files=sorted(directory.iterdir())
    if not files or not all(p.is_file() and re.fullmatch(r'\d{5}\.png',p.name) for p in files):
        raise MotionError('SAM 2 identity masks must be a complete 00000.png, 00001.png ... sequence')
    if [int(p.stem) for p in files]!=list(range(len(files))):
        raise MotionError('SAM 2 mask track contains missing or duplicate frame IDs')
    W,H=resolution
    for f in files:
        with Image.open(f) as im:
            if im.format!='PNG' or im.mode!='L' or im.size!=(W,H):
                raise MotionError('SAM 2 video mask must be L-mode PNG at original video resolution: '+f.name)
    return files


def _mask_at(mask:np.ndarray,xy,radius:int=3):
    if not point(xy):return False
    x,y=map(lambda v:int(round(v)),xy)
    H,W=mask.shape
    if not (0<=x<W and 0<=y<H):return False
    return bool(mask[max(0,y-radius):min(H,y+radius+1),max(0,x-radius):min(W,x+radius+1)].any())


def _validated_candidate(raw,mask):
    kp=raw.get('keypoints',[]); scores=raw.get('keypoint_scores')
    if scores is None or len(kp)<17 or len(scores)<17:return None
    try:
        joints={name:[float(kp[i][0]),float(kp[i][1])] for i,name in enumerate(COCO_17)}
        conf={name:float(scores[i]) for i,name in enumerate(COCO_17)}
    except (TypeError,ValueError,IndexError,KeyError):return None
    if not all(point(joints[n]) and math.isfinite(conf[n]) and .30<=conf[n]<=1.0 for n in NECESSARY):
        return None
    torso=('left_shoulder','right_shoulder','left_hip','right_hip')
    legs=('left_knee','right_knee','left_ankle','right_ankle')
    thor=sum(_mask_at(mask,joints[n]) for n in torso)
    lower=sum(_mask_at(mask,joints[n]) for n in legs)
    if thor<3 or lower<2:return None
    support=thor+lower
    center=[sum(joints[n][i] for n in torso)/4 for i in (0,1)]
    ytop=min(joints[n][1] for n in torso); ybottom=max(joints[n][1] for n in legs)
    height=max(8.,abs(ybottom-ytop))
    score=sum(conf[n] for n in NECESSARY)/len(NECESSARY)
    return {'joints':{n:[round(v,4) for v in joints[n]] for n in COCO_17},
            'scores':{n:round(conf[n],5) for n in COCO_17},
            'coverage':support,'center':center,'height':height,'confidence':score}


def select_identity(result,mask,previous_center=None,previous_height=None):
    candidates=[c for raw in _predictions(result) if (c:=_validated_candidate(raw,mask)) is not None]
    if not candidates:raise MotionError('No MMPose human with reliable joints inside the SAM 2 identity mask')
    candidates.sort(key=lambda a:(a['coverage'],a['confidence']),reverse=True)
    if len(candidates)>1 and candidates[0]['coverage']-candidates[1]['coverage']<2:
        raise MotionError('Ambiguous overlapping people inside SAM 2 mask; refine segmentation prompts')
    best=candidates[0]
    if previous_center is not None:
        d=math.dist(best['center'],previous_center)
        if d>max(15.,max(best['height'],previous_height or 0)*.7):
            raise MotionError(f'MMPose identity center jumps {d:.1f}px between neighboring frames')
    return {'joints':best['joints'],'scores':best['scores']},best['center'],best['height']


def verify_masked_guide(guide,mask_directory,resolution,source_video=None):
    """Cross-check existing real MMPose JSON against SAM 2 video masks offline."""
    mask_files=_load_mask_sequence(mask_directory,resolution)
    frames=guide['frames']
    if len(mask_files)!=len(frames):
        raise MotionError('SAM 2/MMPose mismatch: different frame counts; never interpolate or repeat masks')
    if source_video is not None and guide.get('source_video')!=Path(source_video).name:
        raise MotionError('MMPose guide refers to a different video than SAM 2 identity masks')
    prev=None;prev_h=None
    for i,(f,mask_path) in enumerate(zip(frames,mask_files)):
        with Image.open(mask_path) as im:mask=np.asarray(im)>127
        if mask.sum()<16:raise MotionError(f'SAM 2 tracked actor invisible in frame {i}')
        joint=f['joints']; conf=f.get('scores',{})
        if not all(point(joint.get(n)) and isinstance(conf.get(n),(int,float)) and conf[n]>=.3 for n in NECESSARY):
            raise MotionError(f'MMPose guide has untrusted joints on frame {i}')
        thor=('left_shoulder','right_shoulder','left_hip','right_hip')
        legs=('left_knee','right_knee','left_ankle','right_ankle')
        if sum(_mask_at(mask,joint[n]) for n in thor)<3 or sum(_mask_at(mask,joint[n]) for n in legs)<2:
            raise MotionError(f'MMPose keypoints do not belong to the SAM 2 identity on frame {i}')
        center=[sum(joint[n][j] for n in thor)/4 for j in (0,1)]
        height=max(8,abs(max(joint[n][1] for n in legs)-min(joint[n][1] for n in thor)))
        if prev is not None and math.dist(center,prev)>max(15.,max(height,prev_h)*.7):
            raise MotionError(f'MMPose person swaps identity near frame {i}')
        prev,prev_h=center,height
    return {'identity':'sam2-verified','reference_frames':len(frames),
            'mask_sha256':hashlib.sha256(b''.join(hashlib.sha256(p.read_bytes()).digest() for p in mask_files)).hexdigest()}


def infer_masked_video(video,out,mask_directory,device=None,max_frames=1500):
    """Run real multi-human MMPose, select only the person named by SAM 2 masks."""
    path=Path(video).resolve()
    if not path.is_file():raise MotionError('MMPose source video missing')
    try:
        import cv2
        from mmpose.apis import MMPoseInferencer
    except ImportError as exc:
        raise MotionError('Install official MMPose v1, its human model weights and OpenCV to track crowds') from exc
    cap=cv2.VideoCapture(str(path))
    try:
        if not cap.isOpened():raise MotionError('Cannot decode MMPose/SAM 2 shared video')
        fps=float(cap.get(cv2.CAP_PROP_FPS));count=int(cap.get(cv2.CAP_PROP_FRAME_COUNT))
        W=int(cap.get(cv2.CAP_PROP_FRAME_WIDTH));H=int(cap.get(cv2.CAP_PROP_FRAME_HEIGHT))
    finally:cap.release()
    if not (5<=fps<=240 and W>=16 and H>=16):raise MotionError('MMPose video has invalid FPS/dimensions')
    if count>max_frames:raise MotionError('MMPose reference video exceeds max_frames')
    masks=_load_mask_sequence(Path(mask_directory),(W,H))
    if count>0 and count!=len(masks):
        raise MotionError('MMPose video and SAM 2 mask sequences have different frame counts')
    inferencer=MMPoseInferencer(pose2d='human',device=device) if device else MMPoseInferencer(pose2d='human')
    frames=[];prev=None;prev_h=None
    try:
        for i,result in enumerate(inferencer(str(path),return_vis=False,show=False)):
            if i>=len(masks) or i>=max_frames:raise MotionError('Video has more inferred frames than SAM 2 masks')
            with Image.open(masks[i]) as im:mask=np.asarray(im)>127
            if mask.sum()<16:raise MotionError(f'Empty SAM 2 mask on frame {i}')
            selected,prev,prev_h=select_identity(result,mask,prev,prev_h)
            frames.append({'frame':i,**selected})
    except MotionError:raise
    except Exception as exc:raise MotionError('MMPose/SAM 2 inference failed: '+str(exc)) from exc
    if len(frames)<12 or len(frames)!=len(masks):
        raise MotionError('Missing actual MMPose/SAM 2 frame(s); no substituted poses')
    guide={'engine':'mmpose','format':1,'model':'human','keypoint_schema':'coco17',
           'source_video':path.name,'fps':round(fps,5),'frames':frames,
           'identity_source':'real_sam2_tracked_masks',
           'note':'Reference keypoints only; independently painted 2D/2.5D poses still required'}
    dst=Path(out).resolve();dst.parent.mkdir(parents=True,exist_ok=True)
    dst.write_text(json.dumps(guide,ensure_ascii=False,indent=2),'utf8')
    read_guide(dst)
    verify_masked_guide(guide,mask_directory,(W,H),path)
    return dst
